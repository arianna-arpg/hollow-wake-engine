import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { root, materialize, verifyReference } from './reference-utils.mjs';
import { integrate } from '../adapters/hollow-wake/integrate.mjs';
import { integrateItems } from '../adapters/hollow-wake/integrate-items.mjs';
import { integrateInventoryUi } from '../adapters/hollow-wake/integrate-inventory-ui.mjs';
import { integratePassiveGrants } from '../adapters/hollow-wake/integrate-passive-grants.mjs';
import { integratePassivePolicy } from '../adapters/hollow-wake/integrate-passive-policy.mjs';
import { integrateInventoryHost } from '../adapters/hollow-wake/integrate-inventory-host.mjs';
import { integrateStash } from '../adapters/hollow-wake/integrate-stash.mjs';
import { integrateContainers } from '../adapters/hollow-wake/integrate-containers.mjs';
import { integrateRelicCustody } from '../adapters/hollow-wake/integrate-relic-custody.mjs';
import { integrateRelicActions } from '../adapters/hollow-wake/integrate-relic-actions.mjs';
import { integrateEquipmentActions } from '../adapters/hollow-wake/integrate-equipment-actions.mjs';
import { integrateProgression } from '../adapters/hollow-wake/integrate-progression.mjs';
import { integrateSkillProgression } from '../adapters/hollow-wake/integrate-skill-progression.mjs';
import { integrateSupports } from '../adapters/hollow-wake/integrate-supports.mjs';
import { integrateResources } from '../adapters/hollow-wake/integrate-resources.mjs';
import { integrateResourceEvents } from '../adapters/hollow-wake/integrate-resource-events.mjs';
import { integrateChargedCasting } from '../adapters/hollow-wake/integrate-charged-casting.mjs';
import { integrateInteractiveCasting } from '../adapters/hollow-wake/integrate-interactive-casting.mjs';
import { integrateAmmunition } from '../adapters/hollow-wake/integrate-ammunition.mjs';
import { integrateChannelCasting } from '../adapters/hollow-wake/integrate-channel-casting.mjs';
import { integrateGuardCasting } from '../adapters/hollow-wake/integrate-guard-casting.mjs';
import { integrateResourcePayment } from '../adapters/hollow-wake/integrate-resource-payment.mjs';
import { integrateSkillAdmission } from '../adapters/hollow-wake/integrate-skill-admission.mjs';
import { integrateSkillIntent } from '../adapters/hollow-wake/integrate-skill-intent.mjs';
import { integrateSkillRequest } from '../adapters/hollow-wake/integrate-skill-request.mjs';
const artifacts = path.join(root, '.artifacts');
fs.mkdirSync(artifacts, { recursive: true });
const requested = process.argv.indexOf('--game');
const game = requested < 0 ? path.join(artifacts, 'game-adapter') : path.resolve(process.argv[requested + 1]);
if (requested < 0) {
  const lock = JSON.parse(fs.readFileSync(path.join(root, 'baseline/source-lock.json'), 'utf8'));
  materialize(null, lock, game); verifyReference(game, lock);
}
assert.ok(!fs.existsSync(path.join(game, 'node_modules')), 'Refusing to replace existing dependencies');
integrateItems(game, false); // Check item inputs before changing any game source.
integrateInventoryUi(game, false);
integratePassiveGrants(game, false);
integratePassivePolicy(game, false, true);
integrateInventoryHost(game, false);
integrateStash(game, false);
integrateContainers(game, false);
integrateRelicCustody(game, false);
integrateRelicActions(game, false);
integrateEquipmentActions(game, false);
integrateProgression(game, false);
integrateSkillProgression(game, false);
integrateSupports(game, false);
integrateResources(game, false);
integrateResourceEvents(game, false);
integrateChargedCasting(game, false);
integrateInteractiveCasting(game, false);
integrateAmmunition(game, false);
integrateChannelCasting(game, false);
integrateGuardCasting(game, false);
integrateResourcePayment(game, false);
integrateSkillAdmission(game, false);
integrateSkillIntent(game, false);
integrateSkillRequest(game, false);
// A distinct tool environment: never install into the frozen reference or another checkout's junction.
const tooling = fs.mkdtempSync(path.join(artifacts, 'adapter-tools-'));
for (const file of ['package.json', 'package-lock.json']) fs.copyFileSync(path.join(root, 'reference/tooling', file), path.join(tooling, file));
const npmCli = process.env.npm_execpath ?? path.join(path.dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js');
const npm = (args, cwd) => execFileSync(process.execPath, [npmCli, ...args, '--cache', path.join(artifacts, 'npm-cache')], { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
npm(['ci', '--ignore-scripts', '--no-audit', '--no-fund'], tooling);
const [packed] = JSON.parse(npm(['pack', '--json', '--pack-destination', artifacts], root));
const consumer = path.join(tooling, 'engine-consumer');
fs.mkdirSync(consumer);
fs.writeFileSync(path.join(consumer, 'package.json'), '{"private":true,"type":"module"}');
npm(['install', path.join(artifacts, packed.filename), '--ignore-scripts', '--no-audit', '--no-fund', '--offline'], consumer);
fs.mkdirSync(path.join(tooling, 'node_modules/@hollow-wake'));
fs.symlinkSync(path.join(consumer, 'node_modules/@hollow-wake/engine'), path.join(tooling, 'node_modules/@hollow-wake/engine'), process.platform === 'win32' ? 'junction' : 'dir');
const changes = integrate(game);
const items = integrateItems(game);
changes.files.push(...items.files);
const inventoryUi = integrateInventoryUi(game);
changes.files.push(...inventoryUi.files);
changes.intentionalRepair = inventoryUi.intentionalRepair;
const passiveGrants = integratePassiveGrants(game);
changes.files.push(...passiveGrants.files);
const passivePolicy = integratePassivePolicy(game);
changes.files.push(...passivePolicy.files);
const inventoryHost = integrateInventoryHost(game);
changes.files.push(...inventoryHost.files);
const stash = integrateStash(game);
changes.files.push(...stash.files);
const containers = integrateContainers(game);
changes.files.push(...containers.files);
const relicCustody = integrateRelicCustody(game);
changes.files.push(...relicCustody.files);
const relicActions = integrateRelicActions(game);
changes.files.push(...relicActions.files);
const equipmentActions = integrateEquipmentActions(game);
changes.files.push(...equipmentActions.files);
const progression = integrateProgression(game);
changes.files.push(...progression.files);
const skillProgression = integrateSkillProgression(game);
changes.files.push(...skillProgression.files);
const supports = integrateSupports(game);
changes.files.push(...supports.files);
const resources = integrateResources(game);
changes.files.push(...resources.files);
const resourceEvents = integrateResourceEvents(game);
changes.files.push(...resourceEvents.files);
const chargedCasting = integrateChargedCasting(game);
changes.files.push(...chargedCasting.files);
const interactiveCasting = integrateInteractiveCasting(game);
changes.files.push(...interactiveCasting.files);
const ammunition = integrateAmmunition(game);
changes.files.push(...ammunition.files);
const channelCasting = integrateChannelCasting(game);
changes.files.push(...channelCasting.files);
const guardCasting = integrateGuardCasting(game);
changes.files.push(...guardCasting.files);
const resourcePayment = integrateResourcePayment(game);
changes.files.push(...resourcePayment.files);
const skillAdmission = integrateSkillAdmission(game);
changes.files.push(...skillAdmission.files);
const skillIntent = integrateSkillIntent(game);
changes.files.push(...skillIntent.files);
const skillRequest = integrateSkillRequest(game);
changes.files.push(...skillRequest.files);
fs.symlinkSync(path.join(tooling, 'node_modules'), path.join(game, 'node_modules'), process.platform === 'win32' ? 'junction' : 'dir');
fs.copyFileSync(path.join(root, 'reference/export-lifecycle.ts'), path.join(game, 'balance/export-engine-lifecycle.ts'));
fs.writeFileSync(path.join(artifacts, 'adapter-location.json'), JSON.stringify({ game, tooling, package: packed.filename, integrity: packed.integrity, ...changes }, null, 2));
console.log(`Prepared isolated game adapter: ${game}`);
