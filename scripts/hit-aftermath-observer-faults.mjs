export function applyAftermathFault(tree,fault){
  const[name,section,index,needle,replacement]=fault,node=tree[section==='top'?'top':'inner'][index];assert(node,name);
  const text=node.getText(tree.ast);assert.equal(text.split(needle).length,2,name+' selector');
  const changed=text.replace(needle,replacement);assert.notEqual(changed,text,name);
  return tree.input.slice(0,node.getStart(tree.ast))+changed+tree.input.slice(node.end);
}
