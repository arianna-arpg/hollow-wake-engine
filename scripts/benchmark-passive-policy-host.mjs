import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { root, verifyReference, listFiles } from './reference-utils.mjs';
const reference = path.join(root, '.reference'), lock = JSON.parse(fs.readFileSync(path.join(root, 'baseline/source-lock.json')));
const location = JSON.parse(fs.readFileSync(path.join(root, '.artifacts/adapter-location.json')));
const installed = path.join(location.tooling, 'node_modules/@hollow-wake/engine/dist');
verifyReference(reference, lock);
for (const file of listFiles(path.join(root, 'dist'))) assert.deepEqual(fs.readFileSync(path.join(installed, file)), fs.readFileSync(path.join(root, 'dist', file)), `Stale package: ${file}`);
const target = path.join(reference, 'balance/benchmark-engine-passive-policy-host.ts');
fs.copyFileSync(path.join(root, 'reference/benchmark-passive-policy-host.ts'), target);
execFileSync(process.execPath, ['--import', 'tsx', target, root, location.game, path.join(root, '.artifacts/passive-policy-host-benchmark.json')], { cwd: reference, stdio: 'inherit' });
verifyReference(reference, lock);
