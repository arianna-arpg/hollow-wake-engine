import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { buildItemContent } from './compile-item-content.mjs';
import { root, writeJSON } from './reference-utils.mjs';
const artifacts = path.join(root, '.artifacts'), data = path.join(artifacts, 'item-package');
buildItemContent(data);
const npmCli = process.env.npm_execpath ?? path.join(path.dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js');
const npm = (args, cwd) => execFileSync(process.execPath, [npmCli, ...args, '--cache', path.join(artifacts, 'npm-cache')], { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
const [engine] = JSON.parse(npm(['pack','--json','--pack-destination',artifacts], root));
const [content] = JSON.parse(npm(['pack','--json','--pack-destination',artifacts], data));
assert.ok(content.files.every(f => !/\.(?:js|ts)$/.test(f.path)), 'Item content must remain data only');
const consumer = fs.mkdtempSync(path.join(os.tmpdir(), 'hollow-item-consumer-'));
writeJSON(path.join(consumer, 'package.json'), { private: true, type: 'module' });
npm(['install',path.join(artifacts,engine.filename),path.join(artifacts,content.filename),'--offline','--ignore-scripts','--no-audit','--no-fund'], consumer);
fs.writeFileSync(path.join(consumer, 'run.mjs'), `
import fs from 'node:fs'; import assert from 'node:assert/strict'; import crypto from 'node:crypto';
Math.random = () => { throw new Error('ambient random'); };
globalThis.fetch = () => { throw new Error('network'); };
for (const key of ['window','document','localStorage']) Object.defineProperty(globalThis,key,{get(){throw new Error(key)}});
const core = await import('@hollow-wake/engine');
assert.equal('ItemRules' in core, false, 'Items are a separate runtime entry point');
const { ItemContent, ItemRules } = await import('@hollow-wake/engine/items');
const { createItemHost } = await import('@hollow-wake/engine/items/host');
const read = spec => fs.readFileSync(new URL(import.meta.resolve(spec)));
const bytes = read('@hollow-wake/items/items.json'), manifest = JSON.parse(read('@hollow-wake/items/manifest.json'));
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), manifest.sha256);
const rules = new ItemRules(new ItemContent(JSON.parse(bytes)), 126);
const item = rules.forge({baseId:'ring_lapis',ilvl:21,rarity:'rare',quality:1,affixes:[{id:'attr_intelligence'}]});
const bag = new core.Inventory({w:2,h:2}); const identity = 'actor-1:'+item.uid;
bag.insert({id:identity,w:1,h:1,data:item});
const loaded = core.Inventory.restore(JSON.parse(JSON.stringify(bag.snapshot())));
const pack = JSON.parse(read('@hollow-wake/engine/content/milestone-one.json'));
const engine = new core.Engine(pack,32), hero = engine.character({classId:'magician',passivePoints:1});
const before = hero.attributes.intelligence;
hero.equipInstance({id:identity,name:item.name,category:'ring',slots:['ring1','ring2'],mods:rules.compile(loaded.get(identity).data)},'ring1');
assert.ok(hero.attributes.intelligence>before);
assert.deepEqual(engine.character(JSON.parse(JSON.stringify(hero.snapshot()))).attributes,hero.attributes);
const skill = engine.skill({id:'ruin',level:5,sockets:0,treePoints:0});
assert.ok(engine.resolveHit(hero,skill,engine.target({life:1000})).damage>0);
assert.deepEqual(ItemRules.restore(rules.content,JSON.parse(JSON.stringify(rules.snapshot()))).roll({ilvl:21}),rules.roll({ilvl:21}));
let nextUid=300,draws=0;
const host=createItemHost(rules.content,()=>nextUid++);
assert.equal(host.forge({baseId:'ring_lapis',ilvl:21},()=>{draws++;return .5;}).uid,300);
assert.ok(draws>0);assert.equal(nextUid,301);
console.log(JSON.stringify({itemToInventoryToEquipmentToHit:true,explicitHostPorts:true,contentId:manifest.contentId}));
`);
const result = JSON.parse(execFileSync(process.execPath,['run.mjs'],{cwd:consumer,encoding:'utf8',env:{...process.env,NODE_PATH:''}}));
writeJSON(path.join(artifacts,'item-package-verification.json'),{...result,engineIntegrity:engine.integrity,itemIntegrity:content.integrity,
  itemArchiveBytes:content.size,itemUnpackedBytes:content.unpackedSize});
console.log(JSON.stringify({ ...result, itemArchiveBytes:content.size }));
