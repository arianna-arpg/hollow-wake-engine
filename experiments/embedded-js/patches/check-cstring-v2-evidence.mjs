import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {gunzipSync} from 'node:zlib';
import {root,sha256} from '../../../scripts/reference-utils.mjs';
import {verifyCStringReportV2} from './verify-cstring-v2.mjs';
const directory=path.join(root,'evidence/native-cstring-cleanup/qualification-v2');
const acceptance=JSON.parse(fs.readFileSync(path.join(directory,'acceptance.json')));
assert.equal(acceptance.schemaVersion,1);assert.equal(acceptance.contractRevision,2);
assert.equal(acceptance.productionAdopted,false);assert.equal(acceptance.deviceQualified,false);
for(const[file,digest]of Object.entries(acceptance.sources))assert.equal(sha256(fs.readFileSync(path.join(root,file))),digest,file);
assert.deepEqual(Object.keys(acceptance.files),['windows.json.gz','windows.raw.json.gz','controls.json']);
for(const[file,digest]of Object.entries(acceptance.files))assert.equal(sha256(fs.readFileSync(path.join(directory,file))),digest,file);
const report=JSON.parse(gunzipSync(fs.readFileSync(path.join(directory,'windows.json.gz'))));
assert.equal(report.platform,'win32');
const summary=verifyCStringReportV2(report,fs.readFileSync(path.join(directory,'windows.raw.json.gz')));
const controls=JSON.parse(fs.readFileSync(path.join(directory,'controls.json')));
assert.equal(controls.passed,true);assert.equal(controls.restoredControl,true);assert.equal(controls.controls,16);
assert.equal(new Set(controls.names).size,16);
console.log({...summary,evidenceControls:controls.controls});
